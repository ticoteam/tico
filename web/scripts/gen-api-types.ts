// Writes src/api/schema.d.ts: the person-facing API's types, from the server's OpenAPI v2 document.
// scripts/gen_ui_types.py builds the text in-process from backend/openapi_v2.py (no server);
// this writes it here. One type per component schema, plus
// <Op>Params, <Op>Body and <Op>Response per operation. Generated, never committed.
import { execFileSync } from 'node:child_process';
import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const web = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const repo = resolve(web, '..');
const out = resolve(web, 'src/api/schema.d.ts');

const program = [
  'import sys, warnings',
  'warnings.simplefilter("ignore")',
  'sys.path[:0] = [".", "scripts"]',
  'from gen_ui_types import build',
  'from backend.openapi_v2 import generate',
  'sys.stdout.write(build(generate()))',
].join('\n');

const text = execFileSync(process.env['PYTHON'] ?? 'python3', ['-c', program], {
  cwd: repo,
  encoding: 'utf8',
  maxBuffer: 64 * 1024 * 1024,
  stdio: ['ignore', 'pipe', 'inherit'],
});
const body = text.replace(/^(\/\/.*\n)+/, '');
const header =
  '// Generated by web/scripts/gen-api-types.ts from backend/openapi_v2.py. Do not edit by hand.\n' +
  '// Regenerate with: npm run gen:api\n';

mkdirSync(dirname(out), { recursive: true });
writeFileSync(out, header + body);
console.log(`wrote ${out}`);
