// Writes ../contracts/screen-actions.json: what Tico may ask the open app to do (architecture.md 5), from the action
// registry. The server reads that file on each `show on screen` call (backend/screen_actions.py) and checks the action
// and its input against it. The registry collects actions with import.meta.glob, so it is loaded through Vite.
import { writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createServer } from 'vite';

const web = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const out = resolve(web, '../contracts/screen-actions.json');

const vite = await createServer({
  root: web,
  logLevel: 'error',
  appType: 'custom',
  server: { middlewareMode: true, hmr: false, watch: null },
});
try {
  const { actionsCatalog } = (await vite.ssrLoadModule('/src/actions/registry.ts')) as {
    actionsCatalog: () => unknown[];
  };
  const file = {
    $comment:
      'Generated by web/scripts/gen-screen-actions.ts from the web app’s action registry (npm run gen:screen-actions). ' +
      'Do not edit by hand. What Tico may do on a person’s open app (backend/screen_actions.py); each input is a JSON Schema.',
    actions: actionsCatalog(),
  };
  writeFileSync(out, JSON.stringify(file, null, 2) + '\n');
  console.log(`wrote ${out} (${file.actions.length} actions)`);
} finally {
  await vite.close();
}
