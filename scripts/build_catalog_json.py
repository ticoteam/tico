#!/usr/bin/env python3
"""Build the setup page's role list from the templates, and the copies Tico HQ serves suggestions from.

    backend/company_file/roles.json
                          every role template the tico.team/setup page offers (`hub template list` less the helpers),
                          with its summary and when to suggest it, for the setup page's draft engine

With `--out DIR`, into DIR and nothing else (Tico HQ, in ticoteam/tico-services, has no templates; its sync job runs this
at the latest published Tico release tag):

    DIR/catalog.json      departments and card metadata (no instructions), from templates/groups.yaml and
                          templates/catalog/*/card.yaml, built with backend/recruit_rank.py `build()`, the same
                          function the Tico server uses for its own catalog
    DIR/onboarding-actions.json
                          the engine's actions, vocabulary and limits, the role catalogue and the company models, in one
                          file for the setup page's browser planner
    DIR/recruit_rank.py   a copy of backend/recruit_rank.py, the local recommender both sides fall back to
    DIR/company_file/     a copy of backend/company_file, the draft engine (its scrubber is keys.py)

    python3 scripts/build_catalog_json.py                   # rewrite roles.json
    python3 scripts/build_catalog_json.py --check           # exit 1 when roles.json is stale (a test runs this)
    python3 scripts/build_catalog_json.py --out DIR         # write the copies into DIR
    python3 scripts/build_catalog_json.py --out DIR --check # exit 1 when DIR's copies are stale or missing

Run it after changing a card. The Tico server builds its own template list at run time with backend/recruit_rank.py
`build()`.
"""
import importlib.util
import json
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
TEMPLATES = ROOT / "templates"
SOURCE = ROOT / "backend" / "recruit_rank.py"
ENGINE = ROOT / "backend" / "company_file"
OUT_ROLES = ENGINE / "roles.json"
HEADER = "# Generated by scripts/build_catalog_json.py from backend/recruit_rank.py. Do not edit; edit that file.\n"
ENGINE_HEADER = "# Generated by scripts/build_catalog_json.py from backend/company_file/%s. Do not edit; edit that file.\n"


def _ranker():
    spec = importlib.util.spec_from_file_location("recruit_rank_source", SOURCE)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def cards(catalog_dir=TEMPLATES / "catalog"):
    out = []
    for card in sorted(Path(catalog_dir).glob("*/card.yaml")):
        try:
            document = yaml.safe_load(card.read_text())
        except yaml.YAMLError:
            continue
        if isinstance(document, dict):
            out.append(document)
    return out


def _strings(value):
    return [str(item) for item in value if isinstance(item, (str, int, float)) and str(item).strip()] \
        if isinstance(value, list) else []


def roles(documents):
    """The setup page's role list: every card `hub template list` serves except the helpers, which sit outside the
    org chart. Built-in (`required`) cards are the `core` department and the assistant reads as "Assistant", as the
    page shows them. `tools` are the prerequisites besides hub; `recommend_when` leaves out `always`."""
    out = []
    for card in documents:
        template = str(card.get("template") or "").strip()
        if not template or card.get("kind") == "helper":
            continue
        slug = str(card.get("slug") or template).strip()
        routine = card.get("first_routine") if isinstance(card.get("first_routine"), dict) else {}
        name = str(card.get("name") or template)
        prerequisites = card.get("prerequisites") if isinstance(card.get("prerequisites"), list) else []
        out.append({
            "slug": slug, "template": template, "name": "Assistant" if "{{" in name else name,
            "department": "core" if card.get("required") else str(card.get("group") or card.get("department") or ""),
            "lead": bool(card.get("lead")), "core": bool(card.get("required")),
            "summary": str(card.get("summary") or ""), "when": str(card.get("when") or ""),
            "tags": _strings(card.get("tags")), "pains": _strings(card.get("pains")),
            "recommend_when": [item for item in _strings(card.get("recommend_when")) if item != "always"],
            "first_routine": " · ".join(str(routine.get(key) or "") for key in ("title", "cadence")) if routine else "",
            "tools": sorted({str(item.get("tool")) for item in prerequisites
                             if isinstance(item, dict) and item.get("tool") and item.get("tool") != "hub"}),
            "default": str(card.get("suggest") or "") == "default" and not card.get("required"),
        })
    out.sort(key=lambda role: role["slug"])
    return {"roles": out}


def planner(role_list):
    """onboarding-actions.json: what the browser planner needs to make the same edits as the engine."""
    spec = json.loads((ENGINE / "actions.json").read_text())
    return json.dumps({"format": spec["format"], "vocabulary": spec["vocabulary"], "limits": spec["limits"],
                       "actions": spec["actions"],
                       "models": {path.stem[len("model_"):]: json.loads(path.read_text())
                                  for path in sorted(ENGINE.glob("model_*.json"))},
                       "seats": json.loads((ENGINE / "seats.json").read_text())["seats"],
                       "roles": json.loads(role_list)["roles"]}, indent=1, ensure_ascii=False) + "\n"


def build():
    """{path: text} for the file this script keeps in the repository."""
    return {OUT_ROLES: json.dumps(roles(cards()), indent=1, ensure_ascii=False) + "\n"}


def export(out):
    """{path: text} for every file `--out DIR` writes: the engine's .py files headed as generated, roles.json as just built."""
    out = Path(out)
    groups_file = TEMPLATES / "groups.yaml"
    departments = yaml.safe_load((groups_file if groups_file.is_file() else TEMPLATES / "departments.yaml").read_text()) or {}
    documents = cards()
    role_list = json.dumps(roles(documents), indent=1, ensure_ascii=False) + "\n"
    files = {out / "catalog.json": json.dumps(_ranker().build(departments, documents), indent=1, ensure_ascii=False,
                                              sort_keys=True) + "\n",
             out / "onboarding-actions.json": planner(role_list), out / "recruit_rank.py": HEADER + SOURCE.read_text()}
    for path in sorted(ENGINE.iterdir()):
        if path.suffix == ".py":
            files[out / "company_file" / path.name] = ENGINE_HEADER % path.name + path.read_text()
        elif path.suffix == ".json" and path != OUT_ROLES:
            files[out / "company_file" / path.name] = path.read_text()
    files[out / "company_file" / OUT_ROLES.name] = role_list
    return files


def _shown(path):
    return str(path.relative_to(ROOT)) if path.is_relative_to(ROOT) else str(path)


def main(argv):
    out = None
    if "--out" in argv:
        at = argv.index("--out")
        if at + 1 >= len(argv) or argv[at + 1].startswith("--"):
            print("usage: build_catalog_json.py [--out DIR] [--check]", file=sys.stderr)
            return 2
        out = Path(argv[at + 1]).resolve()
    outputs = export(out) if out else build()
    engine = out / "company_file" if out else None
    if "--check" in argv:
        extra = [path for path in engine.glob("*") if path not in outputs and path.name != "__pycache__"] \
            if engine and engine.is_dir() else []
        stale = [_shown(path) for path, text in outputs.items() if not path.is_file() or path.read_text() != text] \
            + [_shown(path) for path in extra]
        if stale:
            print("stale: " + ", ".join(stale) + "; run python3 scripts/build_catalog_json.py"
                  + (" --out " + str(out) if out else ""), file=sys.stderr)
            return 1
        return 0
    for path in engine.glob("*") if engine and engine.is_dir() else []:
        if path not in outputs and path.is_file():
            path.unlink()
    for path, text in outputs.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text)
    print("%d files: %s" % (len(outputs), ", ".join(sorted({_shown(path.parent if path.parent == engine else path)
                                                             for path in outputs}))))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
