#!/usr/bin/env python3
"""Write ui/types/api.d.ts: TypeScript types for the person-facing API (backend/openapi_v2.py).

The document is built in-process from the same function that writes docs/openapi/v2.json, so no server runs.
Each component schema becomes an exported type; each operation gets <Name>Params, <Name>Body and <Name>Response.
`--check` exits non-zero when the committed file is out of date.
"""
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / 'ui' / 'types' / 'api.d.ts'
HEADER = ('// Generated by scripts/gen_ui_types.py from backend/openapi_v2.py. Do not edit by hand.\n'
          '// Regenerate with: python3 scripts/gen_ui_types.py\n')
SCHEMA_PREFIX = '#/components/schemas/'
PRIMITIVES = {'string': 'string', 'number': 'number', 'integer': 'number', 'boolean': 'boolean', 'null': 'null'}


def literal(value):
    return json.dumps(value)


def ref_name(ref):
    if not ref.startswith(SCHEMA_PREFIX):
        raise ValueError('unsupported reference: ' + ref)
    return ref[len(SCHEMA_PREFIX):]


def union(parts):
    seen = []
    for part in parts:
        if part not in seen:
            seen.append(part)
    return ' | '.join(seen) if seen else 'never'


# openapi_v2 writes a few schemas as bare shorthand letters (items("s")); the served document keeps them as-is.
SHORTHAND = {'s': {'type': 'string'}, 'i': {'type': 'integer'}, 'b': {'type': 'boolean'}, 'o': {'type': 'object'},
             'n': {'type': ['string', 'null']}, 'a': {'type': 'array'}, 'f': {'type': 'number'}}


def ts_type(schema):
    """The TypeScript type for one JSON Schema node (the subset openapi_v2 uses)."""
    if isinstance(schema, str):
        return ts_type(SHORTHAND[schema])
    if schema is True or schema == {}:
        return 'unknown'
    if schema is False:
        return 'never'
    if '$ref' in schema:
        return ref_name(schema['$ref'])
    if 'const' in schema:
        return literal(schema['const'])
    if 'enum' in schema:
        return union([literal(v) for v in schema['enum']])
    if 'allOf' in schema:
        return '(' + ' & '.join(ts_type(s) for s in schema['allOf']) + ')'
    if 'anyOf' in schema:
        return union([ts_type(s) for s in schema['anyOf']])
    if 'oneOf' in schema:
        return union([ts_type(s) for s in schema['oneOf']])
    kind = schema.get('type')
    if isinstance(kind, list):
        return union([ts_type(dict(schema, type=k)) for k in kind])
    if kind in PRIMITIVES:
        return PRIMITIVES[kind]
    if kind == 'array':
        items = schema.get('items')
        return 'Array<' + (ts_type(items) if items is not None else 'unknown') + '>'
    if kind == 'object' or 'properties' in schema or 'additionalProperties' in schema:
        return object_type(schema)
    return 'unknown'


def object_type(schema):
    props = schema.get('properties')
    extra = schema.get('additionalProperties')
    if not props and isinstance(extra, dict):
        return 'Record<string, ' + ts_type(extra) + '>'
    if not props:
        return 'Record<string, unknown>'
    required = set(schema.get('required', []))
    lines = []
    for name in sorted(props):
        optional = '' if name in required else '?'
        lines.append('  %s%s: %s;' % (json.dumps(name) if not re.match(r'^[A-Za-z_]\w*$', name) else name,
                                     optional, ts_type(props[name])))
    if isinstance(extra, dict):
        lines.append('  [key: string]: %s;' % ts_type(extra))
    return '{\n' + '\n'.join(lines) + '\n}'


def response_type(op):
    """The 200 answer: JSON schema when declared, string for event streams and file bytes."""
    ok = op.get('responses', {}).get('200')
    if ok is None:
        return 'void'
    content = ok.get('content', {})
    if 'application/json' in content:
        return ts_type(content['application/json'].get('schema', {}))
    if content:
        return 'string'
    return 'void'


def body_type(op):
    body = op.get('requestBody')
    if not body:
        return 'never'
    content = body.get('content', {})
    if 'application/json' in content:
        return ts_type(content['application/json'].get('schema', {}))
    return 'FormData | Blob'


def params_type(op):
    fields = []
    for param in op.get('parameters', []):
        if param.get('in') not in ('path', 'query', 'header'):
            continue
        optional = '' if param.get('required') or param.get('in') == 'path' else '?'
        name = param['name']
        key = name if re.match(r'^[A-Za-z_]\w*$', name) else json.dumps(name)
        fields.append('  %s%s: %s;' % (key, optional, ts_type(param.get('schema', {}))))
    if not fields:
        return 'Record<string, never>'
    return '{\n' + '\n'.join(sorted(fields)) + '\n}'


def build(document):
    lines = [HEADER]
    schemas = document['components']['schemas']
    for name in sorted(schemas):
        lines.append('export type %s = %s;\n' % (name, ts_type(schemas[name])))
    seen = set(schemas)
    ops = []
    for path, methods in document['paths'].items():
        for method, op in methods.items():
            op_id = op.get('operationId')
            if not op_id:
                raise RuntimeError('operation %s %s has no operationId' % (method.upper(), path))
            ops.append((op_id, method, path, op))
    for op_id, method, path, op in sorted(ops, key=lambda item: item[0]):
        base = op_id[:1].upper() + op_id[1:]
        names = [base + 'Params', base + 'Body', base + 'Response']
        for name in names:
            if name in seen:
                raise RuntimeError('type name %s is used twice' % name)
            seen.add(name)
        lines.append('/** %s %s */' % (method.upper(), path))
        lines.append('export type %s = %s;' % (names[0], params_type(op)))
        lines.append('export type %s = %s;' % (names[1], body_type(op)))
        lines.append('export type %s = %s;\n' % (names[2], response_type(op)))
    return '\n'.join(lines).rstrip() + '\n'


def generate():
    sys.path.insert(0, str(ROOT))
    from backend.openapi_v2 import generate as build_document
    return build(build_document())


if __name__ == '__main__':
    text = generate()
    if '--check' in sys.argv:
        if not OUT.exists() or OUT.read_text() != text:
            sys.exit('ui/types/api.d.ts is stale: run python3 scripts/gen_ui_types.py')
        sys.exit(0)
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(text)
    print('wrote', OUT)
