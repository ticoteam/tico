"""Write backend/tests/fixtures/schema_floor.sql: every table an install of the compatibility floor's release can hold,
with the rows a new database of that release starts with. A dump of a fresh hub at that tag, plus the tables and
columns its source makes on first use.

    python3 scripts/cleanup/gen_upgrade_fixture.py v0.6.0

Run it on the release the floor names (backend/migrations/retired.txt lists the files it shipped) whenever the floor
moves. It checks the tag out in a new folder and starts its code only against a new empty database there.
backend/tests/test_schema_baseline.py upgrades the dump and compares it with a new database.
"""

import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "backend/tests/fixtures/schema_floor.sql"
PROGRAM = """
import sqlite3, sys
from pathlib import Path
sys.path.insert(0, sys.argv[2])
import schema_source as S
from backend.config import Settings
from backend.store import Store
db = Path(sys.argv[1])
Store(Settings(db_path=db)).initialize()
conn = sqlite3.connect(db)
creates, columns = S.statements(".")
S.add_lazy_tables(conn, creates, columns, skip=set(sys.argv[3].split(",")))
conn.commit()
print("\\n".join(conn.iterdump()))
"""
# What the floor's source names only in its old numbered start-up steps, which made these on a still older file before a
# migration dropped them again: no install at the floor has them. `tasks` is here for the columns those steps added
# (type_id, step_id, guest, waiting_on); its real columns are all in the dump.
OLD_STEPS = (
    "approvals,goal_events,market_edges,market_entities,market_events,task_events,turn_usage_segments,turns,"
    "usage_limits,tasks"
)


def main():
    ref = sys.argv[1]
    with tempfile.TemporaryDirectory() as tmp:
        tree = Path(tmp) / "tree"
        subprocess.run(["git", "worktree", "add", "-q", "--detach", str(tree), ref], cwd=ROOT, check=True)
        try:
            dump = subprocess.run(
                [sys.executable, "-c", PROGRAM, str(Path(tmp) / "hub.sqlite"), str(ROOT / "backend/tests"), OLD_STEPS],
                cwd=tree,
                capture_output=True,
                text=True,
                check=True,
            ).stdout
        finally:
            subprocess.run(["git", "worktree", "remove", "--force", str(tree)], cwd=ROOT, check=True)
    start = dump.find("BEGIN TRANSACTION;")
    OUT.write_text(
        f"-- Generated by scripts/cleanup/gen_upgrade_fixture.py {ref}: every table an install of that release can\n"
        "-- hold, including those made on first use. backend/tests/test_schema_baseline.py upgrades it.\n"
        + dump[start:]
    )
    print(f"wrote {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
