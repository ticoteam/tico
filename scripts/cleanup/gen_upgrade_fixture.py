"""Write backend/tests/fixtures/schema_old_main.sql: every table an install of an old commit can hold, under its old
column names. A dump of a fresh hub at that commit, plus the tables and columns its source makes on first use.

    python3 scripts/cleanup/gen_upgrade_fixture.py 8d2e55c7e

Run it on the commit a release is cut from before renames (Release 1's is 8d2e55c7e). It checks the commit out in a new
folder and starts its code only against a new empty database there.
"""

import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "backend/tests/fixtures/schema_old_main.sql"
PROGRAM = """
import sqlite3, sys
from pathlib import Path
sys.path.insert(0, sys.argv[2])
import schema_source as S
from backend.config import Settings
from backend.store import Store
db = Path(sys.argv[1])
Store(Settings(db_path=db)).initialize()
conn = sqlite3.connect(db)
creates, columns = S.statements(".")
S.add_lazy_tables(conn, creates, columns, skip=set(sys.argv[3].split(",")))
conn.commit()
version = conn.execute("PRAGMA user_version").fetchone()[0]
print("\\n".join(conn.iterdump()))
print(f"PRAGMA user_version={version};")
"""
# Tables the old code made only to drop or copy them while it upgraded a still older database: an install has none.
RETIRED = "documents,document_versions,fin_vendor_legacy"


def main():
    ref = sys.argv[1]
    with tempfile.TemporaryDirectory() as tmp:
        tree = Path(tmp) / "tree"
        subprocess.run(["git", "worktree", "add", "-q", "--detach", str(tree), ref], cwd=ROOT, check=True)
        try:
            dump = subprocess.run([sys.executable, "-c", PROGRAM, str(Path(tmp) / "hub.sqlite"),
                                   str(ROOT / "backend/tests"), RETIRED],
                                  cwd=tree, capture_output=True, text=True, check=True).stdout
        finally:
            subprocess.run(["git", "worktree", "remove", "--force", str(tree)], cwd=ROOT, check=True)
    start = dump.find("BEGIN TRANSACTION;")
    OUT.write_text(f"-- Generated by scripts/cleanup/gen_upgrade_fixture.py {ref}: every table an install of that commit can\n"
                   "-- hold, including those made on first use. backend/tests/test_schema_every_table.py upgrades it.\n"
                   + dump[start:])
    print(f"wrote {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
