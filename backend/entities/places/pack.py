# pyright: strict
"""The public places pack: one place tree that every company's Directory uses, read from data/<version>/places.csv.

Countries, US states and territories, US counties and US cities of 50,000 people or more. Each place has a stable id:

    place:<ISO alpha-2>                  country            place:us
    place:us-<USPS>                      state, territory   place:us-ca
    place:us-<USPS>-<county FIPS>        county             place:us-ca-06037
    place:us-<USPS>-<place GEOID>        city               place:us-ca-0644000

A place's parent is the place one level up; countries have none. The data is generated by
scripts/build_places_pack.py from public sources (see data/<version>/pack.json). Do not edit it by hand.

The pack is reference data. A hub writes only the places a record refers to, through ensure_places and an adapter
(see adapter.py for the Directory's tables); it never copies the whole pack.
"""

from __future__ import annotations

import csv
import functools
import sqlite3
import unicodedata
from collections import defaultdict
from collections.abc import Iterable
from pathlib import Path
from typing import NamedTuple, Protocol

DATA_ROOT = Path(__file__).resolve().parent / "data"
VERSION = "2026.11.1"
KINDS = ("country", "state", "territory", "county", "city")
_RANK = {kind: rank for rank, kind in enumerate(KINDS)}


class Place(NamedTuple):
    id: str
    kind: str
    name: str
    parent: str | None
    usps: str | None
    iso_alpha3: str | None
    census_geoid: str | None
    governing_body: str | None
    aliases: tuple[str, ...]


class PlaceAdapter(Protocol):
    """Where ensure_places writes. Both methods are idempotent and return True only when they created a row."""

    def upsert_place(self, conn: sqlite3.Connection, place: Place) -> bool: ...

    def locate(self, conn: sqlite3.Connection, place_id: str, parent_id: str) -> bool: ...


@functools.cache
def load(version: str = VERSION) -> tuple[Place, ...]:
    """Every row of one pack version, in id order. The file is read once per process."""
    with (DATA_ROOT / version / "places.csv").open(encoding="utf-8", newline="") as handle:
        return tuple(
            Place(
                id=row["id"],
                kind=row["kind"],
                name=row["name"],
                parent=row["parent"] or None,
                usps=row["usps"] or None,
                iso_alpha3=row["iso_alpha3"] or None,
                census_geoid=row["census_geoid"] or None,
                governing_body=row["governing_body"] or None,
                aliases=tuple(alias for alias in row["aliases"].split("|") if alias),
            )
            for row in csv.DictReader(handle)
        )


def _norm(text: str) -> str:
    """Case, accents and punctuation ignored: 'Calif.' finds California, 'Sao Paulo' finds São Paulo."""
    plain = unicodedata.normalize("NFKD", text).encode("ascii", "ignore").decode("ascii").casefold()
    return "".join(char for char in plain if char.isalnum())


@functools.cache
def _index(version: str) -> tuple[dict[str, Place], dict[str, tuple[str, ...]]]:
    rows = load(version)
    by_id = {place.id: place for place in rows}
    by_key: dict[str, list[str]] = defaultdict(list)
    for place in rows:
        keys = {_norm(place.name), *(_norm(alias) for alias in place.aliases)}
        # A code names its own place only: 'CA' is California, not the cities and counties inside it.
        if place.kind in ("state", "territory") and place.usps:
            keys.add(_norm(place.usps))
        if place.kind == "country" and place.iso_alpha3:
            keys.add(_norm(place.iso_alpha3))
        for key in keys:
            if key:
                by_key[key].append(place.id)
    return by_id, {key: tuple(ids) for key, ids in by_key.items()}


def lookup(place_id: str, version: str = VERSION) -> Place | None:
    """The place with this id, or None when the pack has no such place."""
    by_id, _ = _index(version)
    return by_id.get(place_id)


def ancestors(place_id: str, version: str = VERSION) -> list[Place]:
    """The chain above a place, nearest first, ending at its country. Raises KeyError for an id the pack lacks."""
    by_id, _ = _index(version)
    parent = by_id[place_id].parent
    chain: list[Place] = []
    while parent is not None:
        if len(chain) > len(by_id):
            raise RuntimeError(f"parent cycle above {place_id}")
        chain.append(by_id[parent])
        parent = by_id[parent].parent
    return chain


def find(
    name: str,
    kind: str | None = None,
    within: str | None = None,
    version: str = VERSION,
) -> list[Place]:
    """Places whose name, alias, USPS code or ISO alpha-3 code matches `name`, ignoring case, accents and punctuation.

    `kind` keeps one kind. `within` keeps the places inside that place id (its descendants; a place is not within
    itself). Results are sorted country first, then by name. An ambiguous name returns every match, e.g. 'Georgia'
    is both a state and a country, and 'LA' is Louisiana and Los Angeles: the caller picks, usually with `kind`.
    """
    if kind is not None and kind not in _RANK:
        raise ValueError(f"kind must be one of {', '.join(KINDS)}, not {kind}")
    by_id, by_key = _index(version)
    found = [by_id[place_id] for place_id in by_key.get(_norm(name), ())]
    if kind is not None:
        found = [place for place in found if place.kind == kind]
    if within is not None:
        found = [place for place in found if any(up.id == within for up in ancestors(place.id, version))]
    return sorted(found, key=lambda place: (_RANK[place.kind], place.name))


def ensure_places(
    conn: sqlite3.Connection,
    place_ids: Iterable[str],
    adapter: PlaceAdapter,
    version: str = VERSION,
) -> list[str]:
    """Write the requested places and every ancestor of each, parents first, through `adapter`.

    Nothing else from the pack is written, and a second call with the same ids writes nothing: each adapter call is
    idempotent. Returns the ids of the rows this call created. Raises KeyError for an id the pack lacks, before writing.
    """
    if isinstance(place_ids, str):
        raise TypeError("pass a list of place ids, not one string")
    by_id, _ = _index(version)
    wanted: dict[str, Place] = {}
    for place_id in place_ids:
        if place_id not in by_id:
            raise KeyError(f"{place_id} is not in places pack {version}")
        for place in (by_id[place_id], *ancestors(place_id, version)):
            wanted[place.id] = place
    created: list[str] = []
    for place in sorted(wanted.values(), key=lambda item: (_RANK[item.kind], item.id)):
        if adapter.upsert_place(conn, place):
            created.append(place.id)
        if place.parent is not None:
            adapter.locate(conn, place.id, place.parent)
    return created
